import { act, fireEvent, screen, waitFor, within } from "@testing-library/react";
import { broadcast, broadcasts, endedBroadcast, FakeEventSource, FakeEventSourceCtor, output, reel } from "../test/fixtures";
import { renderUi } from "../test/render";
import { BroadcastPage } from "./BroadcastPage";

function serve() {
  const calls: { url: string; method: string }[] = [];
  vi.stubGlobal("fetch", vi.fn(async (url: string, init?: RequestInit) => {
    const method = init?.method ?? "GET";
    calls.push({ url, method });
    if (url === "/api/broadcasts/b1/reels") {
      return new Response(JSON.stringify(broadcasts({ revision: 7, broadcasts: [endedBroadcast({ generating: true })] })), { status: 200 });
    }
    if (url === "/api/broadcasts/b1/reels/r1") {
      return new Response(JSON.stringify(broadcasts({ revision: 7, broadcasts: [endedBroadcast({ reels: [] })] })), { status: 200 });
    }
    if (url === "/api/broadcasts/b1/live") {
      return new Response(JSON.stringify({ detail: [{ loc: ["body", "destinations"], msg: "Turn on at least one destination first." }] }), { status: 409 });
    }
    return new Response("{}", { status: 404 });
  }));
  return calls;
}

function push(path: string, doc: unknown) {
  act(() => {
    const source = FakeEventSource.instances.filter((item) => item.url === path && !item.closed).at(-1)!;
    source.open();
    source.emitRaw(JSON.stringify(doc));
  });
}

function show(doc = broadcasts({ broadcasts: [endedBroadcast()] })) {
  renderUi(<BroadcastPage broadcastId="b1" eventSource={FakeEventSourceCtor} retryMs={10} />);
  push("/api/studio/output/stream", output());
  push("/api/broadcasts/stream", doc);
}

beforeEach(() => {
  FakeEventSource.instances = [];
});

test("an ended broadcast shows its stats", () => {
  serve();
  show();
  expect(screen.getByRole("heading", { level: 1, name: "Derby day" })).toBeTruthy();
  const tile = (name: string) => within(screen.getByRole("group", { name }));
  expect(tile("Time on air").getByText("2 min")).toBeTruthy();
  expect(tile("Destinations reached").getByText("2 of 3")).toBeTruthy();
  expect(tile("Audience").getByText("7 votes")).toBeTruthy();
  expect(tile("Audience").getByText("1 poll · 3 questions")).toBeTruthy();
  expect(tile("Match").getByText("1–0")).toBeTruthy();
  expect(tile("Key moments").getByText("1")).toBeTruthy();
  expect(screen.queryByRole("button", { name: "Go live" })).toBeNull();
  expect(screen.queryByRole("button", { name: "End broadcast" })).toBeNull();
});

test("the recording plays here and can be downloaded", () => {
  serve();
  show();
  const recording = within(screen.getByRole("region", { name: "Recording" }));
  const player = recording.getByLabelText("Recording player") as HTMLVideoElement;
  expect(player.getAttribute("src")).toBe("/api/broadcasts/b1/recordings/2026-10-13-140000-rec.mp4");
  const download = recording.getByRole("link", { name: "Download 2026-10-13-140000-rec.mp4" });
  expect(download.getAttribute("download")).toBe("2026-10-13-140000-rec.mp4");
  expect(recording.getByText(/2 min · 5\.0 MB/)).toBeTruthy();
});

test("sessions say how each destination fared, and key moments where they fell", () => {
  serve();
  show();
  const sessions = within(screen.getByRole("region", { name: "Sessions" }));
  expect(sessions.getByText(/Session 1 .* 2 min/)).toBeTruthy();
  expect(sessions.getAllByText("Reached")).toHaveLength(2);
  expect(sessions.getByText("Failed")).toBeTruthy();
  const moments = within(screen.getByRole("region", { name: "Key moments" }));
  expect(moments.getByText("23'")).toBeTruthy();
  expect(moments.getByText("Goal · Northbridge FC (1–0)")).toBeTruthy();
  expect(moments.getByText("Top corner!")).toBeTruthy();
  expect(moments.getByText("0:42 into the broadcast")).toBeTruthy();
});

test("reels play, download with their post to copy, and more are generated by the AI agents", async () => {
  const calls = serve();
  show();
  const reels = within(screen.getByRole("region", { name: "Reels" }));
  const card = within(reels.getByRole("article", { name: "Reel: GOAL! Northbridge FC score in the 23'" }));
  expect((card.getByLabelText(/^Play/) as HTMLVideoElement).getAttribute("src")).toBe("/api/broadcasts/b1/reels/r1.mp4");
  expect(card.getByText("#Goal")).toBeTruthy();
  expect(card.getByText("AI agents")).toBeTruthy();
  expect(card.getByText("15 s from 0:34")).toBeTruthy();
  expect(card.getByRole("link").getAttribute("href")).toBe("/api/broadcasts/b1/reels/r1.mp4");
  expect(reels.getByText(/Highlight Editor picks the moments/)).toBeTruthy();

  fireEvent.click(reels.getByRole("button", { name: "Generate reels with AI agents" }));
  await waitFor(() => expect(calls).toContainEqual({ url: "/api/broadcasts/b1/reels", method: "POST" }));
  expect(await reels.findByText("The agents are picking moments and cutting clips…")).toBeTruthy();
  expect((reels.getByRole("button", { name: "Generate reels with AI agents" }) as HTMLButtonElement).disabled).toBe(true);
});

test("a reel being cut or that failed says so, and a reel can be deleted", async () => {
  const calls = serve();
  show(broadcasts({
    ai: false,
    broadcasts: [endedBroadcast({ reels: [reel(), reel({ id: "r2", title: "Cutting", state: "rendering" }), reel({ id: "r3", title: "Broken", state: "failed", reason: "ffmpeg could not cut the clip: oops", agent: "template" })] })],
  }));
  const reels = within(screen.getByRole("region", { name: "Reels" }));
  expect(within(reels.getByRole("article", { name: "Reel: Cutting" })).getByText("Cutting the clip…")).toBeTruthy();
  const broken = within(reels.getByRole("article", { name: "Reel: Broken" }));
  expect(broken.getByText("ffmpeg could not cut the clip: oops")).toBeTruthy();
  expect(broken.getByText("Template")).toBeTruthy();
  expect(reels.getByRole("button", { name: "Generate reels" })).toBeTruthy();
  expect(reels.getByText(/No AI model is set/)).toBeTruthy();
  const first = within(reels.getByRole("article", { name: "Reel: GOAL! Northbridge FC score in the 23'" }));
  fireEvent.click(first.getByRole("button", { name: "Delete this reel" }));
  await waitFor(() => expect(calls).toContainEqual({ url: "/api/broadcasts/b1/reels/r1", method: "DELETE" }));
});

test("a ready broadcast goes live from here, and a refusal is shown", async () => {
  const calls = serve();
  show(broadcasts({ broadcasts: [broadcast()], current_id: "b1" }));
  expect(screen.getByText(/No recording yet/)).toBeTruthy();
  expect((screen.getByRole("button", { name: "Generate reels with AI agents" }) as HTMLButtonElement).disabled).toBe(true);
  fireEvent.click(screen.getByRole("button", { name: "Go live" }));
  await waitFor(() => expect(calls).toContainEqual({ url: "/api/broadcasts/b1/live", method: "POST" }));
  expect(await screen.findByText("Turn on at least one destination first.")).toBeTruthy();
});

test("a broadcast that is gone says so", () => {
  serve();
  show(broadcasts());
  expect(screen.getByText(/This broadcast no longer exists/)).toBeTruthy();
});
